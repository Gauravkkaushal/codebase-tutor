"""Configuration for a target repository (.codebase-tutor/config.json)."""
from __future__ import annotations

import copy
import json
import os
from pathlib import Path

from . import DATA_DIR

DEFAULT_CONFIG = {
    "version": 1,
    "language": "en",
    # Glob patterns (fnmatch on repo-relative POSIX paths). Include wins over default exclude.
    "include": [],
    "exclude": [],
    "default_excluded_dirs": [
        ".git", ".hg", ".svn", DATA_DIR, "node_modules", "bower_components", "jspm_packages",
        "vendor", "third_party", "dist", "build", "out", ".next", ".nuxt", ".svelte-kit", ".turbo",
        "coverage", ".nyc_output", "__pycache__", ".pytest_cache", ".mypy_cache", ".ruff_cache",
        ".tox", ".venv", "venv", "env", ".eggs", "site-packages", ".gradle", "target", ".idea",
        ".vscode", ".cache", ".parcel-cache", "storybook-static", "Pods", "DerivedData",
    ],
    "max_file_bytes": 1_000_000,
    "parse_jobs": 0,  # 0 = auto
    "snapshot": {"store_blobs": True, "max_blob_store_mb": 500},
    "report": {"embed_source_budget_kb": 6000, "max_symbols_indexed": 30000, "max_graph_nodes": 400},
    "tests": {"timeout_seconds": 600},
}


def data_dir(root: Path) -> Path:
    return Path(root) / DATA_DIR


def load_config(root: Path) -> dict:
    cfg = copy.deepcopy(DEFAULT_CONFIG)
    path = data_dir(root) / "config.json"
    if path.exists():
        try:
            user = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            user = {}
        _merge(cfg, user)
    return cfg


def _merge(base: dict, extra: dict) -> None:
    for k, v in extra.items():
        if isinstance(v, dict) and isinstance(base.get(k), dict):
            _merge(base[k], v)
        else:
            base[k] = v


def init_data_dir(root: Path) -> tuple[Path, bool]:
    """Create .codebase-tutor/ layout. Returns (path, created_now)."""
    d = data_dir(root)
    created = not d.exists()
    for sub in ("knowledge/flows", "knowledge/explanations", "knowledge/contexts", "knowledge/changes",
                "snapshots/manifests", "snapshots/blobs", "runs/tests", "runs/runtime", "reports", "cache"):
        (d / sub).mkdir(parents=True, exist_ok=True)
    cfg_path = d / "config.json"
    if not cfg_path.exists():
        user_cfg = {"version": 1, "language": "en", "include": [], "exclude": []}
        cfg_path.write_text(json.dumps(user_cfg, indent=2) + "\n", encoding="utf-8")
    gi = d / ".gitignore"
    if not gi.exists():
        # Keep heavy/derived data out of VCS by default; config + explanations may be committed.
        gi.write_text("cache/\nsnapshots/\nruns/\nknowledge/index.db*\nreports/\n", encoding="utf-8")
    readme = d / "README.md"
    if not readme.exists():
        readme.write_text(
            "# .codebase-tutor\n\nGenerated by Codebase Tutor. Safe to delete; it is rebuilt by `ct scan`.\n"
            "`config.json` and `knowledge/explanations/` contain human/agent-authored content you may commit.\n",
            encoding="utf-8")
    return d, created


def env_flag(name: str) -> bool:
    return os.environ.get(name, "").lower() in ("1", "true", "yes")
